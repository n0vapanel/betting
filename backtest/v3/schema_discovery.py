from __future__ import annotations

import io
import sys
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / "backtest/cache/v3"


def describe_csv(path: Path, chunksize: int = 50000) -> str:
    sample = pd.read_csv(path, nrows=5)
    columns = list(sample.columns)
    state = {
        c: {"present": 0, "missing": 0, "sum": 0.0, "min": None, "max": None,
            "numeric": pd.api.types.is_numeric_dtype(sample[c]), "values": set(), "capped": False}
        for c in columns
    }
    count = 0
    for chunk in pd.read_csv(path, chunksize=chunksize, low_memory=False):
        count += len(chunk)
        for column in columns:
            values = chunk[column].dropna()
            item = state[column]
            item["present"] += len(values)
            item["missing"] += int(chunk[column].isna().sum())
            if not len(values):
                continue
            if item["numeric"]:
                values = pd.to_numeric(values, errors="raise")
                low, high = float(values.min()), float(values.max())
                item["sum"] += float(values.sum())
            else:
                low, high = str(values.astype(str).min()), str(values.astype(str).max())
            item["min"] = low if item["min"] is None else min(item["min"], low)
            item["max"] = high if item["max"] is None else max(item["max"], high)
            if len(item["values"]) <= 20:
                item["values"].update(str(x) for x in values.drop_duplicates().iloc[:21])
                if len(item["values"]) > 20:
                    item["capped"] = True
                    item["values"] = set(sorted(item["values"])[:21])
    out = io.StringIO()
    out.write(f"## {path.name}\n\n")
    out.write(f"- Bytes: {path.stat().st_size:,}\n- Rows: {count:,}\n- Columns: {len(columns)}\n")
    out.write(f"- Column names: `{', '.join(columns)}`\n\n")
    out.write("### First five rows (unmodified CSV values)\n\n```csv\n")
    out.write(pd.read_csv(path, nrows=5, dtype=str).to_csv(index=False))
    out.write("```\n\n### Basic statistics and unique-value samples\n\n")
    out.write("Distinct samples are capped at 20; 'more' is not an exact distinct count.\n\n")
    out.write("| column | inferred dtype | non-null | missing | min | max | numeric mean | unique sample |\n")
    out.write("|---|---|---:|---:|---|---|---:|---|\n")
    for c, item in state.items():
        mean = item["sum"] / item["present"] if item["numeric"] and item["present"] else None
        unique = ", ".join(sorted(item["values"])[:20])
        if item["capped"]:
            unique += ", … (more)"
        unique = unique.replace("|", "\\|")
        out.write(f"| `{c}` | {sample[c].dtype} | {item['present']} | {item['missing']} | "
                  f"{item['min']} | {item['max']} | {f'{mean:.6g}' if mean is not None else '—'} | {unique} |\n")
    return out.getvalue()


def discover(output: Path = ROOT / "v3_SCHEMA.md") -> str:
    lines = [
        "# V3 cached-source schema discovery\n",
        "Generated by `backtest/v3/schema_discovery.py`; all inputs are read-only. "
        "The large player file is never loaded by this discovery command.\n",
    ]
    for filename in ["game_odds.csv", "team_boxscores.csv"]:
        lines.append(describe_csv(CACHE / filename))
    samples, kinds = [], {}
    for chunk in pd.read_csv(CACHE / "game_odds.csv", chunksize=50000, dtype={"game_id": str}):
        category = chunk["odds_date"].where(chunk["odds_date"].isin(["open", "close"]), "timestamp/other")
        category = category.where(chunk["odds_date"].notna(), "missing")
        for key, value in category.value_counts().items():
            kinds[str(key)] = kinds.get(str(key), 0) + int(value)
        samples.append(chunk.loc[chunk.game_date.str[:10].eq("2022-03-01")])
    march = pd.concat(samples, ignore_index=True)
    lines.extend([
        "## Odds marker categories\n", f"`{kinds}`\n",
        "## March 1, 2022: five rows per game\n\n```csv\n",
        march.groupby("game_id", sort=False).head(5).to_csv(index=False), "```\n",
        "## Semantic and temporal interpretation\n",
        "- `game_id`: NBA identifier; normalize to a ten-character zero-padded string before joining.\n"
        "- `game_date`: game-calendar date, not tipoff; values mix naive midnight ISO and midnight-with-Z encodings.\n"
        "- `odds_date`: literal `open`, literal `close`, or a UTC timestamp for an odds update. "
        "The marker rows do not contain publication timestamps.\n"
        "- `last_fetched`: retrospective scrape time (including 2026 for 2022 games), never a feature or an availability time.\n"
        "- `decimal_home/away`: rounded quoted decimal prices; `moneyline_home/away`: signed American prices. "
        "Probability calculations convert American prices without decimal rounding.\n"
        "- `source_url`: source provenance only. Home/away identity is cross-checked through NBA game identifiers and schedule metadata.\n"
        "- Team boxscore counting and advanced columns describe the completed game, not pregame knowledge. "
        "Only strictly previous dates enter rolling features. `min` is elapsed game minutes (48 in regulation), "
        "unlike the NBA team-log total player minutes (240).\n"
        "- All `*_rank`, `gp_rank`, `w_rank`, `l_rank`, `w_pct_rank`, `available_flag`, outcomes, "
        "and current-game quarter scores are excluded from predictors. Rank fields may encode retrospective context.\n"
        "- Quarter columns `q1_*` through `q4_*` are regulation-quarter statistics. Quarter consistency is computed "
        "within prior completed games and then rolled forward; overtime is not treated as a fifth quarter.\n"
        "- The player schema is inspected separately in feature construction, using selected columns and 50,000-row chunks. "
        "Only 2021–22 regular-season records through the backtest horizon are retained.\n"
        "- Current-game movement, steam, update counts and TeamRankings close are diagnostic-only. Their historical "
        "team-side rolling values may enter a later game's features, with an explicit strictly-prior-date check.\n",
    ])
    text = "\n".join(lines)
    output.write_text(text)
    return text


if __name__ == "__main__":
    sys.stdout.write(discover())
