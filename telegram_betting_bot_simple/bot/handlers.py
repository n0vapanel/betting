"""Command and callback handlers for the Telegram betting bot.

This module implements the conversation flow for selecting a sport,
entering a date, choosing between single and multi predictions, and
ultimately displaying results generated by the prediction engine.  It
also defines generic `/start`, `/help` and `/cancel` commands as well
as a catch‑all for unknown commands.

State management is handled via a `SessionManager` stored in
``application.bot_data``, and predictions are computed by a
`PredictionEngine` instance (also stored in ``bot_data``).  Each
callback updates the user's session and advances the conversation to
the next stage.  When the predictions are displayed, the session is
reset and the conversation terminates.
"""

from __future__ import annotations

import datetime
from typing import Optional

from telegram import (
    Update,
    InlineKeyboardButton,
    InlineKeyboardMarkup,
)
from telegram.error import BadRequest
from telegram.ext import (
    Application,
    CommandHandler,
    MessageHandler,
    CallbackQueryHandler,
    ContextTypes,
    ConversationHandler,
    filters,
)

from ..config import Config
from .session_manager import SessionManager, UserSession

# Conversation state identifiers.  Telegram's ConversationHandler uses
# integer constants to track which handler should be invoked next.
SELECT_SPORT, SELECT_DATE, SELECT_TYPE = range(3)


async def start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    """Begin the conversation and ask the user to choose a sport.

    This entry point resets any existing session and presents an inline
    keyboard with the supported sports.  Selecting a sport triggers
    ``sport_selected``.
    """
    chat_id = update.effective_chat.id if update.effective_chat else 0
    # Reset the session to start fresh
    session_manager: SessionManager = context.application.bot_data["session_manager"]
    session_manager.reset_session(chat_id)

    # Define the sports we support.  The callback data will be the sport code.
    sports = [
        ("NBA", "nba"),
        ("NHL", "nhl"),
        ("Soccer", "soccer"),
        ("Tennis", "tennis"),
        ("Baseball", "baseball"),
        ("Football", "football"),
        ("Racing", "racing"),
    ]
    keyboard = [
        [InlineKeyboardButton(name, callback_data=code) for name, code in sports[i:i + 2]]
        for i in range(0, len(sports), 2)
    ]
    reply_markup = InlineKeyboardMarkup(keyboard)
    welcome_message = (
        "Welcome to the Sports Betting Bot!\n"
        "Please select a sport to begin."
    )
    if update.message:
        await update.message.reply_text(welcome_message, reply_markup=reply_markup)
    else:
        # For safety: handle the case where start is triggered via callback
        await update.callback_query.edit_message_text(welcome_message, reply_markup=reply_markup)
    return SELECT_SPORT


async def help_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    """Provide a list of available commands and brief instructions."""
    help_text = (
        "Available commands:\n"
        "/start – begin a new prediction request\n"
        "/help – display this help message\n"
        "/cancel – cancel the current conversation\n\n"
        "After issuing /start, you will be prompted to choose a sport, a date, "
        "and whether you want single or multi predictions."
    )
    if update.message:
        await update.message.reply_text(help_text)


async def unknown_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    """Handle any unknown commands outside the conversation."""
    if update.message:
        await update.message.reply_text(
            "Sorry, I didn't understand that command. Type /help for assistance."
        )


async def expired_menu(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    """Answer taps on buttons whose conversation ended or was lost when the bot restarted."""
    if update.callback_query:
        try:
            await update.callback_query.answer(
                "This menu has expired. Send /start to begin again.", show_alert=True
            )
        except BadRequest:
            pass  # Tapped too long ago for Telegram to accept an answer


async def cancel(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    """Cancel the current conversation and reset the session."""
    chat_id = update.effective_chat.id if update.effective_chat else 0
    session_manager: SessionManager = context.application.bot_data.get("session_manager")
    if session_manager:
        session_manager.reset_session(chat_id)
    if update.message:
        await update.message.reply_text(
            "Your request has been cancelled. Use /start to begin again."
        )
    return ConversationHandler.END


async def sport_selected(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    """Handle selection of a sport via callback query and ask for the date."""
    query = update.callback_query
    if not query:
        return ConversationHandler.END
    await query.answer()
    sport_code = query.data  # e.g. 'nba'
    chat_id = query.message.chat_id
    # Store the selected sport in the user's session
    session_manager: SessionManager = context.application.bot_data["session_manager"]
    session = session_manager.get_session(chat_id)
    session.sport = sport_code
    # Ask user for the date
    prompt = (
        "Please enter the date for which you want predictions in YYYY-MM-DD format.\n"
        "You can also type 'today' to use the current date."
    )
    await query.message.reply_text(prompt)
    return SELECT_DATE


async def date_entered(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    """Parse the entered date and ask the user to choose prediction type."""
    chat_id = update.effective_chat.id if update.effective_chat else 0
    user_input = update.message.text.strip().lower() if update.message and update.message.text else ""
    # Determine the date
    match_date: Optional[datetime.date]
    if user_input in {"today", "now"}:
        match_date = datetime.date.today()
    else:
        try:
            match_date = datetime.datetime.strptime(user_input, "%Y-%m-%d").date()
        except ValueError:
            await update.message.reply_text(
                "The date format is invalid. Please enter a date in YYYY-MM-DD format or type 'today'."
            )
            return SELECT_DATE
    # Store date in session
    session_manager: SessionManager = context.application.bot_data["session_manager"]
    session = session_manager.get_session(chat_id)
    session.match_date = match_date
    # Ask user to choose prediction type
    keyboard = [[
        InlineKeyboardButton("Single", callback_data="single"),
        InlineKeyboardButton("Multi", callback_data="multi"),
    ]]
    reply_markup = InlineKeyboardMarkup(keyboard)
    await update.message.reply_text(
        "Do you want single game predictions or a multi/bet combo?",
        reply_markup=reply_markup,
    )
    return SELECT_TYPE


# Telegram rejects text messages longer than this, counted in UTF-16 code units.
TELEGRAM_MESSAGE_LIMIT = 4096


def split_message(lines: list[str], limit: int = TELEGRAM_MESSAGE_LIMIT) -> list[str]:
    """Join ``lines`` into as few messages as fit Telegram's length limit, never splitting a line."""
    messages: list[str] = []
    current = ""
    for line in lines:
        candidate = f"{current}\n{line}" if current else line
        if current and len(candidate.encode("utf-16-le")) // 2 > limit:
            messages.append(current)
            current = line
        else:
            current = candidate
    if current:
        messages.append(current)
    return messages


def format_prediction(prediction: dict) -> str:
    """Render one engine prediction, e.g. ``Celtics @ Lakers → Lakers (Middle, 62%)``."""
    winner = prediction.get("winner", "")
    probability = prediction.get("probabilities", {}).get(winner)
    confidence = f", {probability:.0%}" if probability is not None else ""
    return (
        f"{prediction.get('away_team', '?')} @ {prediction.get('home_team', '?')}"
        f" → {winner} ({prediction.get('tier', '')}{confidence})"
    )


async def prediction_type_selected(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    """Generate and display predictions based on the user's selections."""
    query = update.callback_query
    if not query:
        return ConversationHandler.END
    await query.answer()
    selected_type = query.data  # 'single' or 'multi'
    chat_id = query.message.chat_id
    # Update session with prediction type
    session_manager: SessionManager = context.application.bot_data["session_manager"]
    session = session_manager.get_session(chat_id)
    session.prediction_type = selected_type
    # Retrieve prediction engine and compute predictions
    pred_engine = context.application.bot_data["pred_engine"]
    # Use today's date if none provided
    match_date = session.match_date or datetime.date.today()
    sport_code = session.sport or ""
    # If sport not selected, prompt restart
    if not sport_code:
        await query.message.reply_text(
            "Sport not selected. Please start again with /start."
        )
        return ConversationHandler.END
    # Call the prediction engine.  It returns a list of dictionaries.
    try:
        predictions = pred_engine.get_predictions(sport_code, match_date)
    except Exception as e:
        await query.message.reply_text(
            f"An error occurred while generating predictions: {e}"
        )
        session_manager.reset_session(chat_id)
        return ConversationHandler.END
    # Format results
    if not predictions:
        messages = ["No predictions available for the selected sport and date."]
    else:
        lines = ["Here are your predictions:"]
        for p in predictions:
            lines.append(f"• {format_prediction(p)}")
        messages = split_message(lines)
    for message in messages:
        await query.message.reply_text(message)
    # Reset session
    session_manager.reset_session(chat_id)
    return ConversationHandler.END


def setup_handlers(application: Application, config: Config) -> None:
    """Register conversation and command handlers with the application.

    This function instantiates the session manager and prediction engine,
    stores them in ``application.bot_data`` for later use, and sets up
    a conversation handler to manage the multi‑step prediction flow.
    """
    # Create shared objects and store them in bot_data
    session_manager = SessionManager()
    # Instantiate prediction engine with the API keys from config
    from ..engine.prediction_engine import PredictionEngine
    pred_engine = PredictionEngine(
        api_sports_key=config.api_sports_key or config.sports_api_key,
        odds_api_key=config.odds_api_key,
        news_api_key=config.news_api_key,
    )
    application.bot_data["session_manager"] = session_manager
    application.bot_data["pred_engine"] = pred_engine
    application.bot_data["config"] = config

    # Conversation handler for prediction workflow
    conv_handler = ConversationHandler(
        entry_points=[CommandHandler("start", start)],
        states={
            SELECT_SPORT: [CallbackQueryHandler(sport_selected)],
            SELECT_DATE: [MessageHandler(filters.TEXT & ~filters.COMMAND, date_entered)],
            SELECT_TYPE: [CallbackQueryHandler(prediction_type_selected)],
        },
        fallbacks=[CommandHandler("cancel", cancel), CommandHandler("help", help_command)],
    )
    application.add_handler(conv_handler)
    # Button taps the conversation didn't claim (e.g. on a menu from before a restart)
    application.add_handler(CallbackQueryHandler(expired_menu))
    # Standalone help and cancel commands outside of conversation
    application.add_handler(CommandHandler("help", help_command))
    application.add_handler(CommandHandler("cancel", cancel))
    # Catch all other commands with the unknown command handler
    application.add_handler(MessageHandler(filters.COMMAND, unknown_command))
